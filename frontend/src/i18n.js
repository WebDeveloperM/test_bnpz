// Savol/variant matnini tanlangan tilda qaytaradi.
// Tarjima bo'lmasa asosiy tildagi matn ko'rsatiladi — xodim hech qachon bo'sh
// savol ko'rmaydi, faqat o'sha savol tarjima qilinmaganini bilib qoladi.
export function tx(obj, lang) {
  if (!obj) return "";
  return (lang && obj.text_i18n && obj.text_i18n[lang]) || obj.text || "";
}

// "Moslashtirish" savolida o'ng ustun yozuvini tanlangan tilda ko'rsatadi.
// Tanlanadigan QIYMAT o'zgarmaydi (asosiy tildagi matn) — shu sabab til
// almashtirilganda xodimning tanlovi ham, baholash ham buzilmaydi.
export function matchLabel(q, value, lang) {
  return (lang && q.match_i18n && q.match_i18n[value] && q.match_i18n[value][lang]) || value;
}
